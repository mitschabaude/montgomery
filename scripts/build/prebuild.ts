/**
 * Writes the Wasm modules of prebuilt curves, see src/prebuilt, as TS modules
 * with the bytes in base64.
 */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { fieldModule, glvScalarModule } from "../../src/generate.ts";
import { prebuiltCurves } from "../../src/prebuilt/curves.ts";

const dir = new URL("../../src/prebuilt/wasm/", import.meta.url);
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });

const base64 = (bytes: Uint8Array) => Buffer.from(bytes).toString("base64");

for (let [curve, params] of Object.entries(prebuiltCurves)) {
  let { modulus: p, order: q, endomorphism } = params;
  let { beta, lambda } = endomorphism!;
  let field29 = fieldModule({ p, beta, backend: "29-bit" }).toBytes();
  let fieldWide = fieldModule({ p, beta, backend: "wide" }).toBytes();
  let scalar = glvScalarModule({ q, lambda, w: 29 }).toBytes();
  let source = [
    `// Generated by scripts/build/prebuild.ts: the Wasm modules of ${curve}, in base64.`,
    `export const field = {`,
    `  "29-bit": "${base64(field29)}",`,
    `  wide: "${base64(fieldWide)}",`,
    `};`,
    `export const scalar = "${base64(scalar)}";`,
    ``,
  ].join("\n");
  writeFileSync(new URL(`${curve}.ts`, dir), source);
}
console.log("prebuilt modules: src/prebuilt/wasm/");
